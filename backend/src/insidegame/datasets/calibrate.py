"""Command-line calibration report: simulate many matches and compare their statistics with reference bands.

Usage: python -m insidegame.datasets.calibrate --matches 480 --out docs/CALIBRATION.md
It writes nothing but the Markdown report, so it can run in CI or before a release to check simulator realism; an
expected threat (xT) sanity section follows the reference bands.
"""

import argparse
import itertools
from datetime import date
from pathlib import Path

from insidegame.analytics.xt_grid import XT_FIT_MATCHES, XT_GRID
from insidegame.datasets.calibration import calibrate, calibration_table
from insidegame.datasets.rows import build_tables
from insidegame.datasets.xt_sanity import sanity_table, xt_sanity
from insidegame.simulation.engine import simulate_match
from insidegame.simulation.roster import CLUB_PRESETS, build_fixture

DEFAULT_MATCHES: int = 480
DEFAULT_START_SEED: int = 1
DEFAULT_OUTPUT: Path = Path("docs/CALIBRATION.md")


def report(matches: int, start_seed: int) -> str:
    """Simulate matches over every home and away pairing and return the Markdown calibration report."""
    pairings = list(itertools.permutations(CLUB_PRESETS, 2))
    tables = [build_tables(simulate_match(build_fixture(*pairings[i % len(pairings)], start_seed + i)))
              for i in range(matches)]
    rows = calibrate([t.match for t in tables], (row for t in tables for row in t.events))
    checks = xt_sanity([t.match for t in tables], (row for t in tables for row in t.events), XT_GRID)
    within = sum(row.within for row in rows)
    return f"""<!--
Calibration report for the Inside the Game match simulator, generated by insidegame.datasets.calibrate.
It compares statistics over many simulated matches with approximate top-flight reference bands.
Regenerate it after changing the simulator; the numbers are reproducible from the seeds below.
-->

# Simulator Calibration

Generated {date.today().isoformat()} from {matches} matches (seeds {start_seed} to {start_seed + matches - 1}, every
home and away pairing of the {len(CLUB_PRESETS)} fictional clubs). {within} of {len(rows)} metrics fall inside their band.

{calibration_table(rows)}

Reference bands are approximate typical ranges for top European leagues, used as sanity checks rather than exact
targets. Home advantage comes from a shot-volume factor (home sides create more chances), so goals stay in line
with the independent xG model.

## Expected threat (xT) sanity

The xT grid (12 x 8 cells) is fitted by value iteration to {XT_FIT_MATCHES} of our own simulated matches with
`python -m insidegame.datasets.xt_fit`; it is flatter than grids fitted to real leagues because simulated
possessions take many actions per shot. {sum(c.holds for c in checks)} of {len(checks)} checks hold.

{sanity_table(checks)}
"""


def main() -> None:
    """Parse arguments and write the calibration report."""
    parser = argparse.ArgumentParser(description="Check simulator realism against reference bands.")
    parser.add_argument("--matches", type=int, default=DEFAULT_MATCHES)
    parser.add_argument("--start-seed", type=int, default=DEFAULT_START_SEED)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    args.out.write_text(report(args.matches, args.start_seed), encoding="utf-8")
    print(args.out)


if __name__ == "__main__":
    main()
